const (
	npowers    = 87
	steppowers = 8
	firstpower = -348 // 10 ^ -348

	expmax = -32
	expmin = -60
)

const (
	fracmask  = 0x000FFFFFFFFFFFFF
	expmask   = 0x7FF0000000000000
	hiddenbit = 0x0010000000000000
	signmask  = 0x8000000000000000
	expbias   = 1023 + 52
)

// fp is fpconv's Fp: a fraction and a binary exponent.
type fp struct {
	frac uint64
	exp  int
}

