var tens = [20]uint64{
	10000000000000000000, 1000000000000000000, 100000000000000000,
	10000000000000000, 1000000000000000, 100000000000000,
	10000000000000, 1000000000000, 100000000000,
	10000000000, 1000000000, 100000000,
	10000000, 1000000, 100000,
	10000, 1000, 100,
	10, 1,
}

func absv(n int) int {
	if n < 0 {
		return -n
	}
	return n
}

func minv(a, b int) int {
	if a < b {
		return a
	}
	return b
}

func findCachedPow10(exp int, k *int) fp {
	const oneLogTen = 0.30102999566398114

	approx := int(float64(-(exp + npowers)) * oneLogTen)
	idx := (approx - firstpower) / steppowers

	for {
		current := exp + powersTen[idx].exp + 64

		if current < expmin {
			idx++
			continue
		}

		if current > expmax {
			idx--
			continue
		}

		*k = firstpower + idx*steppowers

		return powersTen[idx]
	}
}

func buildFp(d float64) fp {
	bits := math.Float64bits(d)

	var value fp
	value.frac = bits & fracmask
	value.exp = int((bits & expmask) >> 52)

	if value.exp != 0 {
		value.frac += hiddenbit
		value.exp -= expbias
	} else {
		value.exp = -expbias + 1
	}

	return value
}

func normalize(value *fp) {
	for value.frac&hiddenbit == 0 {
		value.frac <<= 1
		value.exp--
	}

	const shift = 64 - 52 - 1
	value.frac <<= shift
	value.exp -= shift
}

func getNormalizedBoundaries(value *fp, lower, upper *fp) {
	upper.frac = (value.frac << 1) + 1
	upper.exp = value.exp - 1

	for upper.frac&(hiddenbit<<1) == 0 {
		upper.frac <<= 1
		upper.exp--
	}

	const uShift = 64 - 52 - 2

	upper.frac <<= uShift
	upper.exp = upper.exp - uShift

	lShift := 1
	if value.frac == hiddenbit {
		lShift = 2
	}

	lower.frac = (value.frac << lShift) - 1
	lower.exp = value.exp - lShift

	lower.frac <<= lower.exp - upper.exp
	lower.exp = upper.exp
}

func multiply(a, b *fp) fp {
	const lomask = 0x00000000FFFFFFFF

	ahBl := (a.frac >> 32) * (b.frac & lomask)
	alBh := (a.frac & lomask) * (b.frac >> 32)
	alBl := (a.frac & lomask) * (b.frac & lomask)
	ahBh := (a.frac >> 32) * (b.frac >> 32)

	tmp := (ahBl & lomask) + (alBh & lomask) + (alBl >> 32)
	// round up
	tmp += 1 << 31

	return fp{
		frac: ahBh + (ahBl >> 32) + (alBh >> 32) + (tmp >> 32),
		exp:  a.exp + b.exp + 64,
	}
}

func roundDigit(digits []byte, ndigits int, delta, rem, kappa, frac uint64) {
	for rem < frac && delta-rem >= kappa &&
		(rem+kappa < frac || frac-rem > rem+kappa-frac) {

		digits[ndigits-1]--
		rem += kappa
	}
}

func generateDigits(value, upper, lower *fp, digits []byte, K *int) int {
	wfrac := upper.frac - value.frac
	delta := upper.frac - lower.frac

	var one fp
	one.frac = 1 << uint(-upper.exp)
	one.exp = upper.exp

	part1 := upper.frac >> uint(-one.exp)
	part2 := upper.frac & (one.frac - 1)

	idx, kappa := 0, 10
	// 1000000000
	for divp := 10; kappa > 0; divp++ {

		div := tens[divp]
		digit := part1 / div

		if digit != 0 || idx != 0 {
			digits[idx] = byte(digit) + '0'
			idx++
		}

		part1 -= digit * div
		kappa--

		tmp := (part1 << uint(-one.exp)) + part2
		if tmp <= delta {
			*K += kappa
			roundDigit(digits, idx, delta, tmp, div<<uint(-one.exp), wfrac)

			return idx
		}
	}

	// 10
	unit := 18

	for {
		part2 *= 10
		delta *= 10
		kappa--

		digit := part2 >> uint(-one.exp)
		if digit != 0 || idx != 0 {
			digits[idx] = byte(digit) + '0'
			idx++
		}

		part2 &= one.frac - 1
		if part2 < delta {
			*K += kappa
			roundDigit(digits, idx, delta, part2, one.frac, wfrac*tens[unit])

			return idx
		}

		unit--
	}
}

func grisu2(d float64, digits []byte, K *int) int {
	w := buildFp(d)

	var lower, upper fp
	getNormalizedBoundaries(&w, &lower, &upper)

	normalize(&w)

	var k int
	cp := findCachedPow10(upper.exp, &k)

	w = multiply(&w, &cp)
	upper = multiply(&upper, &cp)
	lower = multiply(&lower, &cp)

	lower.frac++
	upper.frac--

	*K = -k

	return generateDigits(&w, &upper, &lower, digits, K)
}

func emitDigits(digits []byte, ndigits int, dest []byte, K int, neg bool) []byte {
	exp := absv(K + ndigits - 1)

	if K >= 0 && exp < 15 {
		dest = append(dest, digits[:ndigits]...)
		for i := 0; i < K; i++ {
			dest = append(dest, '0')
		}

		// add a .0 to mark this as a float.
		return append(dest, '.', '0')
	}

	// write decimal w/o scientific notation
	if K < 0 && (K > -7 || exp < 10) {
		offset := ndigits - absv(K)
		// fp < 1.0 -> write leading zero
		if offset <= 0 {
			offset = -offset
			dest = append(dest, '0', '.')
			for i := 0; i < offset; i++ {
				dest = append(dest, '0')
			}

			return append(dest, digits[:ndigits]...)
		}

		// fp > 1.0
		dest = append(dest, digits[:offset]...)
		dest = append(dest, '.')

		return append(dest, digits[offset:ndigits]...)
	}

	// write decimal w/ scientific notation
	negDigit := 0
	if neg {
		negDigit = 1
	}
	ndigits = minv(ndigits, 18-negDigit)

	dest = append(dest, digits[0])

	if ndigits > 1 {
		dest = append(dest, '.')
		dest = append(dest, digits[1:ndigits]...)
	}

	dest = append(dest, 'e')

	if K+ndigits-1 < 0 {
		dest = append(dest, '-')
	} else {
		dest = append(dest, '+')
	}

	cent := 0

	if exp > 99 {
		cent = exp / 100
		dest = append(dest, byte(cent)+'0')
		exp -= cent * 100
	}
	if exp > 9 {
		dec := exp / 10
		dest = append(dest, byte(dec)+'0')
		exp -= dec * 10
	} else if cent != 0 {
		dest = append(dest, '0')
	}

	return append(dest, byte(exp%10)+'0')
}

// fpconvDtoa is fpconv_dtoa: the spelling Ruby's JSON generator writes for a
// Float. Non-finite values never reach it; encodeNumber refuses them first,
// as Ruby's generator does.
func fpconvDtoa(d float64) string {
	var digits [18]byte

	dest := make([]byte, 0, 32)
	neg := false

	if math.Float64bits(d)&signmask != 0 {
		dest = append(dest, '-')
		neg = true
	}

	if d == 0.0 {
		return string(append(dest, '0', '.', '0'))
	}

	K := 0
	ndigits := grisu2(d, digits[:], &K)

	return string(emitDigits(digits[:], ndigits, dest, K, neg))
}
